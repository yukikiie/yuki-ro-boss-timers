export function hasReferenceOriginalPortrait(bossId: string): boolean {
  return Object.hasOwn(REFERENCE_PORTRAITS, bossId);
}

export function ReferenceOriginalPortrait({
  bossId,
  className,
}: {
  bossId: string;
  className?: string;
}) {
  const instanceId = useId().replace(/:/g, "");
  const portrait = REFERENCE_PORTRAITS[bossId];
  if (!portrait) return null;

  const [left, top, width, height] = portrait.bounds;
  const boundsId = `reference-portrait-bounds-${instanceId}`;
  const outlineId = `reference-portrait-outline-${instanceId}`;

  return (
    <svg
      className={className}
      viewBox={`${left} ${top} ${width} ${height}`}
      width="100%"
      height="100%"
      preserveAspectRatio="xMidYMax meet"
      overflow="hidden"
      aria-hidden="true"
      focusable="false"
      data-original-portrait={bossId}
    >
      <defs>
        <clipPath id={boundsId} clipPathUnits="userSpaceOnUse">
          <rect x={left} y={top} width={width} height={height} />
        </clipPath>
        <clipPath id={outlineId} clipPathUnits="userSpaceOnUse">
          {portrait.outlines.map((outline, index) => (
            <path key={index} d={outline} />
          ))}
        </clipPath>
      </defs>
      <g clipPath={`url(#${boundsId})`}>
        <g clipPath={`url(#${outlineId})`}>
          <image
            href="/art/ro-b-reference-source.png"
            x="0"
            y="0"
            width="1448"
            height="1086"
          />
        </g>
      </g>
    </svg>
  );
}
